# -*- coding: utf-8 -*-
"""gen_site_data.py -- mirror site/data/*.trace.json into a JS registry.

The replay site (``site/index.html``) must work when opened directly from
disk (``file://``), where browsers block ``fetch()`` of local files.  The
canonical artifacts remain ``data/*.trace.json`` (RTF v1); this script
mirrors them into a single deterministic, script-loadable registry:

    window.ROT_TRACES = { "<id>": <trace>, ... };

loaded via a plain ``<script>`` tag -- so the gallery works offline with no
build step and no server.  When the site is served over HTTP (GitHub
Pages), ``app.js`` prefers ``fetch('data/<id>.trace.json')`` and falls back
to the registry, so the JSON files stay the source of truth.

Deterministic: trace ids sorted, JSON keys sorted, stable separators -- the
same inputs always produce the same bytes.

Pure stdlib; Python 3.6+.

Usage:
    python scripts/gen_site_data.py [SITE_DIR]     # default: <repo>/site
"""

from __future__ import print_function

import json
import os
import sys

__all__ = ["generate", "generate_data"]


def _repo_root():
    """Absolute path of the repository root (parent of scripts/)."""
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _read_trace(path):
    with open(path, "r") as fh:
        return json.load(fh)


def generate_data(data_dir):
    """Mirror ``data_dir/*.trace.json`` into ``data_dir/traces.js``.

    Returns ``(out_path, trace_ids)`` where ``trace_ids`` is the sorted list
    of trace ids (the file stems without the ``.trace.json`` suffix).
    """
    if not os.path.isdir(data_dir):
        raise SystemExit("ERROR: no data dir: %s" % data_dir)

    entries = {}
    for name in sorted(os.listdir(data_dir)):
        if not name.endswith(".trace.json"):
            continue
        trace_id = name[: -len(".trace.json")]
        entries[trace_id] = _read_trace(os.path.join(data_dir, name))

    payload = dict((k, entries[k]) for k in sorted(entries))
    body = json.dumps(payload, indent=2, sort_keys=True)
    out = (
        "/* GENERATED by scripts/gen_site_data.py -- do not edit by hand.\n"
        " * Mirrors data/*.trace.json (RTF v1) into a script-loadable registry\n"
        " * so the gallery works over file:// (where fetch is blocked).\n"
        " * Regenerate:  python scripts/gen_site_data.py\n"
        " */\n"
        "window.ROT_TRACES = " + body + ";\n"
    )
    out_path = os.path.join(data_dir, "traces.js")
    with open(out_path, "w") as fh:
        fh.write(out)
    return out_path, sorted(entries)


def generate(site_dir):
    """Mirror ``<site_dir>/data/*.trace.json`` into ``data/traces.js``.

    Thin wrapper over :func:`generate_data` for the conventional site layout
    (a ``data/`` subdirectory under the site root).
    """
    return generate_data(os.path.join(site_dir, "data"))


def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    site_dir = argv[0] if argv else os.path.join(_repo_root(), "site")
    out_path, ids = generate(site_dir)
    print("  registry  : %s" % out_path)
    print("  traces    : %s" % (", ".join(ids) if ids else "(none)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
