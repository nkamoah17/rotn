# -*- coding: utf-8 -*-
"""64_replay_reference.py -- E4: replay the E2 events against the reference.

Runs the step-3 command of the E4 plan entirely LOCALLY (no AWS):

  1. generates out/e4-schema.cedarschema -- the AgentCore-namespace schema
     (OAuthUser / IamEntity / UnauthenticatedUser principals, Gateway
     entity, TransferTarget___transfer action whose request context
     carries input.amount: Long).  This is a LOCAL artifact mirroring the
     gateway-generated schema shape (runbook assumption 1); `dogwood
     validate` is the guard, and its result is recorded verbatim below;
  2. renders the meta's live policy template with the real gateway ARN
     ({{GATEWAY_ARN}} -> arn) into out/e4-policy.rendered.dw -- an
     unrendered placeholder can never match the trace's real ARN, which
     would silently read as "all DENY" (scope mismatch);
  3. runs `dogwood validate` FIRST (the guard) and records the result
     verbatim;
  3b. if the as-is text fails validate ONLY because of the event-field
      mismatch (this dogwood build's built-in event schema declares
      callerPrincipal/callerResource/input.amount/requestId/sessionId --
      NOT eventResource, which the live policy's temporal predicate
      names), additionally builds the field-adapted twin
      (eventResource -> callerResource) into out/e4-policy-adapted.dw,
      validates it, and makes IT the primary reading; the as-is run is
      kept under out/e4-as-is/ as evidence (its expected signature is
      all-ALLOW, since the predicate cannot match any event as-is on
      this build).  If validate passes on the as-is text, no twin is
      built and the as-is run is the only one;
  4. runs `python -m rot replay --oracle dogwood --events out/events.jsonl
     --policy <rendered or adapted> --policy-schema out/e4-schema.cedarschema
     --out out/e4/` (the existing single-mode oracle path);
  5. prints the read of the reference's per-fire decisions (per run):
       * reference DENIES fires #3-#5  -> SPEC-CONFORMANT (reflexive
         window; the live gateway's $300 admission is the gap to explain);
       * reference DENIES only #4-#5   -> LIVE/REFERENCE GAP (the reference
         itself is non-reflexive -- the live $300 is consistent with it);
       * reference ADMITS all         -> PREDICATE-MISMATCH EVIDENCE
         (hypothesis A: the predicate never matched a recorded event);
     plus a fourth, setup-level signature discovered while verifying this
     script: reference DENIES all -> SCOPE MISMATCH (the permit never
     applies; fix the policy/trace identity and re-run);
  6. records the dogwood binary path + `dogwood --version`, the validate
     result, and the per-fire decisions in out/e4-report.json.

Usage:  python 64_replay_reference.py [events.jsonl]   (default out/events.jsonl)
Exit:   0 = replayed + recorded (the reading is data, not a pass/fail gate);
        3 = hard error (common.die).

Python 3.6 compatible (repo convention: stdlib only, %-formatting).
Nothing here touches AWS: E4 is the local half of the live investigation.
"""

