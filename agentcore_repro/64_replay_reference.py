# The E4 schema artifact (a LOCAL mirror of the gateway-generated schema
# shape, runbook assumption 1).  Verified against the local dogwood build:
# with the action context carrying input.amount, the spend-cap policies
# type-check and replay correctly -- on a 5 x $100 trace the request-sum
# (correct) policy decides ALLOW/ALLOW/DENY x3 (reflexive, spec-conformant)
# and the response-sum (buggy) policy ALLOW x3 / DENY x2 (non-reflexive).
# NOTE: the reference build's built-in EVENT schema declares
# callerPrincipal/callerResource/input.amount/requestId/sessionId -- NOT
# eventResource -- so the as-is live policy text fails `dogwood validate`
# on that one event-field selection only; step 3b above adapts the field
# and records BOTH runs in out/e4-report.json.
SCHEMA = """// E4 local schema artifact -- generated by 64_replay_reference.py.
// Types the AgentCore spend-cap policy (TransferTarget___transfer) so the
// local dogwood build can validate + replay it.  LOCAL artifact mirroring
// the gateway-generated schema shape (runbook assumption 1); the
// `dogwood validate` result is recorded in out/e4-report.json.
namespace AgentCore {
  type TransferInput = {
    amount: Long
  };

  type TransferOutput = {  };

  type SystemContext = {
    now: datetime
  };

  entity Gateway;

  entity IamEntity = {
    id: String
  };

  entity OAuthUser = {
    id: String
  } tags String;

  entity UnauthenticatedUser;

  action "TransferTarget___transfer" in [Action::"CallTool"] appliesTo {
    principal: [IamEntity, OAuthUser, UnauthenticatedUser],
    resource: [Gateway],
    context: {
      input: TransferInput,
      output?: TransferOutput,
      system: SystemContext
    }
  };

  action "CallTool" in [Action::"Mcp"] appliesTo {
    principal: [OAuthUser, IamEntity, UnauthenticatedUser],
    resource: [Gateway],
    context: {
      system: SystemContext
    }
  };

  action "Mcp" appliesTo {
    principal: [OAuthUser, IamEntity, UnauthenticatedUser],
    resource: [Gateway],
    context: {
      system: SystemContext
    }
  };
}
"""


def find_dogwood():
    """Resolve the dogwood binary (env > known builds > PATH); None if absent."""
    env = os.environ.get("DOGWOOD_BIN")
    if env and os.path.isfile(env):
        return env
    for cand in DOGWOOD_CANDIDATES:
        if os.path.isfile(cand):
            return cand
    return shutil.which("dogwood")


def dogwood_version(binary):
    """``dogwood --version`` output (one line), or 'unknown'."""
    try:
        p = subprocess.run([binary, "--version"], stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT, timeout=30)
        return (p.stdout or b"").decode("utf-8", "replace").strip()
    except (OSError, ValueError, subprocess.SubprocessError):
        return "unknown"


def sha256_file(path):
    """SHA-256 hex digest of a file's bytes (streamed, size-agnostic)."""
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _fires_from_decisions(decisions):
    """Map the reference's decision lines to a {fire_number: ALLOW|DENY}
    dict.  Fire k (1-based) is the request at trace timepoint @2(k-1), so
    a decision line @N maps to fire N // 2 + 1."""
    fires = {}
    for d in decisions:
        n = d.get("seq")
        if isinstance(n, int):
            fires[n // 2 + 1] = d.get("decision", "?")
    return fires


def _validate_note(validate_ok, validate_out):
    """Context for the all-allow reading: was the schema the problem?"""
    out = validate_out or ""
    if validate_ok:
        return ("dogwood validate PASSED, so this is a runtime field "
                "mismatch, not a schema error (hypothesis A -- check the "
                "E1 findings for the live policy).")
    note = "dogwood validate FAILED: " + (out[:400] or "(no output)")
    if "eventResource" in out:
        note += (" The policy references the field `eventResource`, which "
                 "this dogwood build's event schema does not declare (it "
                 "declares callerResource) -- the reference cannot match "
                 "the policy's predicate on this build.")
    return note


def _adapt_field_mismatch(text, validate_out):
    """Detect the one validate failure this local build can adapt.

    dogwood's built-in event schema declares a fixed event-field set; if
    the policy's temporal predicate names a field it does not declare,
    the error reads:

      mentions field `eventResource`, which is not declared on that
      event (declared fields: callerPrincipal, callerResource,
      input.amount, requestId, sessionId)

    The AgentCore spend-cap policies name exactly that one field
    (``eventResource``), and this build declares ``callerResource``
    instead -- so the only adaptation worth attempting is
    ``eventResource`` -> ``callerResource``.  Returns
    ``(adapted_text, unknown_field, declared_fields)`` or
    ``(None, None, None)`` for any other failure (which stays as-is).
    """
    import re
    m = re.search(r"mentions field `(\w+)`, which is not declared on "
                  r"that event\s*\(declared fields: ([^)]*)\)",
                  validate_out or "")
    if not m:
        return None, None, None
    unknown = m.group(1)
    declared = [f.strip() for f in m.group(2).split(",") if f.strip()]
    if unknown != "eventResource" or "callerResource" not in declared:
        return None, None, None
    if "eventResource" not in (text or ""):
        return None, None, None
    return (text.replace("eventResource", "callerResource"),
            unknown, declared)


def _replay_events(events_path, policy_path, schema_path, out_dir):
    """The step-3 command (``rot replay --oracle dogwood --events`` ...)
    into out_dir; returns (rc, output)."""
    if not os.path.isdir(out_dir):
        os.makedirs(out_dir)
    return C.run([sys.executable, "-m", "rot", "replay",
                  "--oracle", "dogwood",
                  "--events", events_path,
                  "--policy", policy_path,
                  "--policy-schema", schema_path,
                  "--out", out_dir], check=False)


def _decisions_from_dir(out_dir):
    """The reference's decision lines from <out_dir>/reference-replay.json."""
    report_path = os.path.join(out_dir, "reference-replay.json")
    if not os.path.isfile(report_path):
        return []
    try:
        with open(report_path, "r") as f:
            reports = json.load(f)
    except (IOError, OSError, ValueError):
        return []
    if not reports:
        return []
    ref = reports[0].get("dogwood_reference_buggy") or {}
    return ref.get("decisions") or []


def e4_read(decisions, meta, validate_ok, validate_out):
    """The E4 three-way read of the reference's per-fire decisions
    (plus the all-DENY setup signature).  Returns (label, detail)."""
    fires = _fires_from_decisions(decisions)
    if not fires:
        return ("NO REFERENCE DECISIONS",
                "The reference produced no decision lines (replay failed "
                "or the trace was empty). See the raw output under out/e4/"
                " and the validate result in out/e4-report.json.")
    n = max(fires)
    admitted = [f for f in sorted(fires) if fires[f] == "ALLOW"]
    denied = [f for f in sorted(fires) if fires[f] == "DENY"]

    if not denied:
        return ("PREDICATE-MISMATCH EVIDENCE (hypothesis A)",
                "The reference admitted EVERY fire: its temporal predicate "
                "never matched a recorded event, so the sum is empty "
                "(0 <= cap) and the permit holds trivially on each fire. "
                + _validate_note(validate_ok, validate_out))
    if not admitted:
        return ("SCOPE-MISMATCH EVIDENCE (the policy never applies)",
                "The reference denied EVERY fire: the permit's scope never "
                "matched (Cedar default-deny when no policy applies) -- "
                "e.g. the ARN placeholder was not rendered, or the "
                "action/resource identity differs from the trace. This is "
                "a replay-setup finding, not a window-semantics reading; "
                "fix the policy/trace identity and re-run.")
    first_denied = denied[0]
    if first_denied == 3 and set(range(3, n + 1)) <= set(denied):
        return ("SPEC-CONFORMANT REFERENCE (reflexive window)",
                "The reference admitted exactly the in-cap fires (#1-%d) "
                "and denied from fire #%d: evaluation at position i "
                "includes the current event (spec SS6, j <= i). The live "
                "gateway's $300 admission is then the live-vs-reference "
                "gap to explain (runbook SS7 hypotheses B/C)."
                % (first_denied - 1, first_denied))
    if first_denied == 4 and set(range(4, n + 1)) <= set(denied):
        return ("LIVE/REFERENCE GAP (non-reflexive window)",
                "The reference itself admitted fire #3 (prior sum $200 "
                "<= $200) and denied only fire #%d onward: its window is "
                "NON-REFLEXIVE (evaluation at i reads j < i). The live "
                "gateway's $300 admission is then CONSISTENT with the "
                "reference -- the gap is reference-vs-spec, not "
                "live-vs-reference." % first_denied)
    return ("MIXED PATTERN -- inspect",
            "Reference admitted fires %s and denied %s; that is not one "
            "of the canonical readings (all-allow / DENY from #3 / DENY "
            "from #4 / all-deny). Inspect out/e4/reference-replay.json "
            "and the validate output." % (admitted, denied))


def main():
    events_path = os.path.join(C.OUT_DIR, "events.jsonl")
    if len(sys.argv) > 1:
        events_path = sys.argv[1]
    events_dir = os.path.dirname(os.path.abspath(events_path))
    meta_path = os.path.join(events_dir, "events-meta.json")
    if not (os.path.isfile(events_path) and os.path.isfile(meta_path)):
        C.die("E2 recording missing: need %s + %s\n"
              "  run 31_fire_sequential.py first (E2), or pass the events "
              "path as the first argument." % (events_path, meta_path))

    with open(meta_path, "r") as f:
        meta = json.load(f)

    binary = find_dogwood()
    if binary is None:
        C.die("dogwood binary not found (set DOGWOOD_BIN or build it; "
              "see docs/03-build-dogwood.md)")
    version = dogwood_version(binary)
    C.ensure_out()

    # 1) the meta's live policy template, rendered with the real ARN
    tpl = meta.get("policy_path_abs")
    if not tpl or not os.path.isfile(tpl):
        tpl = os.path.join(C.HERE, meta.get("policy_path") or "")
    if not os.path.isfile(tpl):
        C.die("policy template not found: %r (events-meta.json "
              "policy_path_abs/policy_path)" % tpl)
    with open(tpl, "r") as f:
        text = f.read()
    arn = meta.get("gateway_arn") or meta.get("resource")
    if not arn:
        C.die("events-meta.json has no gateway_arn -- cannot render "
              "{{GATEWAY_ARN}} (an unrendered placeholder can never "
              "match the trace's real ARN)")
    rendered = text.replace("{{GATEWAY_ARN}}", arn)
    rendered_path = C.write_text("e4-policy.rendered.dw", rendered)
    if "{{GATEWAY_ARN}}" in rendered:
        C.log("WARNING: rendered policy STILL contains {{GATEWAY_ARN}}")
    C.log("policy  : %s  (%s twin, rendered ARN)"
          % (meta.get("policy_path"), meta.get("policy_which")))
    C.log("schema  : out/e4-schema.cedarschema (AgentCore local artifact)")

    # 2) the schema artifact + dogwood validate FIRST (the guard)
    schema_path = C.write_text("e4-schema.cedarschema", SCHEMA)
    C.log("validate: dogwood validate --policy-schema <schema> <policy>")
    rc_val, out_val = C.run([binary, "validate", "--policy-schema",
                             schema_path, rendered_path], check=False)
    C.log("validate(as-is): %s (rc=%d)"
          % ("OK" if rc_val == 0 else "FAILED", rc_val))

    # 2b) the field-mismatch fallback (step 3b of the docstring): if the
    #     as-is text fails validate ONLY because this reference build's
    #     event schema does not declare `eventResource`, build the
    #     field-adapted twin and make it the primary reading.
    adapted_path = None
    rc_val2, out_val2 = None, None
    if rc_val != 0:
        adapted_text, unknown, declared_fields = \
            _adapt_field_mismatch(rendered, out_val)
        if adapted_text is not None:
            adapted_path = C.write_text("e4-policy-adapted.dw",
                                       adapted_text)
            C.log("adapt   : `%s` -> `callerResource` (the reference "
                  "event schema declares: %s)"
                  % (unknown, ", ".join(declared_fields)))
            rc_val2, out_val2 = C.run([binary, "validate",
                                       "--policy-schema", schema_path,
                                       adapted_path], check=False)
            C.log("validate(adapted): %s (rc=%d)"
                  % ("OK" if rc_val2 == 0 else "FAILED", rc_val2))
            if rc_val2 != 0:
                C.log("WARNING: the adapted twin also fails validation; "
                      "falling back to the as-is replay only")
                adapted_path = None
                rc_val2, out_val2 = None, None
        else:
            C.log("validate(as-is) failed for a reason other than the "
                  "known event-field mismatch; replaying the as-is text")

    # 3) the step-3 command(s): the primary reading into out/e4/, the
    #    as-is run kept under out/e4-as-is/ when the twin is primary.
    e4_dir = os.path.join(C.OUT_DIR, "e4")
    runs = {}

    def _replay(policy_path, out_dir, v_ok, v_out, v_rc):
        C.log("replay  : rot replay --oracle dogwood --events %s"
              " --policy %s  (into %s)"
              % (os.path.basename(events_path),
                 os.path.basename(policy_path),
                 os.path.relpath(out_dir, C.OUT_DIR)))
        rc, out = _replay_events(events_path, policy_path,
                                 schema_path, out_dir)
        decs = _decisions_from_dir(out_dir)
        lab, det = e4_read(decs, meta, v_ok, v_out)
        return {"policy": os.path.basename(policy_path),
                "out_dir": os.path.relpath(out_dir, C.OUT_DIR),
                "validate": {"ok": v_ok, "rc": v_rc, "output": v_out},
                "replay_rc": rc,
                "replay_output_tail": (out or "")[-2000:],
                "decisions": decs,
                "reading": lab,
                "reading_detail": det}

    if adapted_path is not None:
        runs["as_is"] = _replay(rendered_path,
                                os.path.join(C.OUT_DIR, "e4-as-is"),
                                False, out_val, rc_val)
        runs["field_adapted"] = _replay(adapted_path, e4_dir,
                                        True, out_val2, rc_val2)
        primary = "field_adapted"
    else:
        runs["as_is"] = _replay(rendered_path, e4_dir,
                                rc_val == 0, out_val, rc_val)
        primary = "as_is"

    pr = runs[primary]
    decisions = pr["decisions"]
    label, detail = pr["reading"], pr["reading_detail"]

    C.write_json("e4-report.json", {
        "script": "64_replay_reference.py",
        "control": "E4",
        "generated_at_utc": C.now_iso(),
        "dogwood": {"binary": binary, "version": version},
        "policy": {
            "which": meta.get("policy_which"),
            "template": meta.get("policy_path"),
            "template_sha256": meta.get("policy_sha256"),
            "rendered": "e4-policy.rendered.dw",
            "rendered_sha256": sha256_file(rendered_path),
            "rendered_arn": arn,
            "adapted": ("e4-policy-adapted.dw"
                        if adapted_path is not None else None),
            "adapted_sha256": (sha256_file(adapted_path)
                               if adapted_path is not None else None),
            "field_map": ({"eventResource": "callerResource"}
                          if adapted_path is not None else None),
        },
        "events": {
            "file": os.path.basename(events_path),
            "meta_file": os.path.basename(meta_path),
            "session": meta.get("session_id"),
            "fired_at_utc": meta.get("fired_at_utc"),
            "n_fires": (len(decisions) if decisions else
                        meta.get("nfires")),
        },
        "schema": {"file": "e4-schema.cedarschema",
                   "sha256": sha256_file(schema_path)},
        "runs": runs,
        "reference_decisions": decisions,
        "reading": label,
        "reading_detail": detail,
        "reading_source": primary,
        "note": ("E4 is the local half of the investigation: it replays "
                 "E2's recorded sequence against the local dogwood "
                 "reference build (binary + version recorded above) and "
                 "reads the per-fire decisions. Nothing here touched "
                 "AWS."),
    })

    print("\n" + "=" * 68)
    print("  E4  dogwood   : %s" % version)
    print("  E4  binary    : %s" % binary)
    for name in sorted(runs):
        r = runs[name]
        print("  E4  [%-14s] validate=%-6s replay_rc=%s  -> %s"
              % (name, "OK" if r["validate"]["ok"] else "FAILED",
                 r["replay_rc"], r["reading"]))
    print("  " + "-" * 64)
    print("  E4  READING   : %s" % label)
    print("                  (source: %s)" % primary)
    print("  " + "-" * 64)
    for line in detail.splitlines() or [detail]:
        print("  %s" % line)
    print("=" * 68)
    raw = "  ".join("out/%s/" % runs[n]["out_dir"] for n in sorted(runs))
    print("wrote out/e4-report.json  (raw: %s)" % raw)
    print("\nE4 is the local half of the investigation -- nothing here "
          "touched AWS.")


if __name__ == "__main__":
    main()